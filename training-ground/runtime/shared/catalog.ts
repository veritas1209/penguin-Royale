export function rarityLabel(item:ItemDef){
 if(
  (item.baseId??item.id)==='underbarrel-launcher' ||
  (item.caliber??item.id)==='ammo-40'
 )return '';

 if(item.category==='attachment')
  return attachmentQualityLabel(item);

 if(item.ammoGrade)
  return AMMO_GRADE_LABELS[item.ammoGrade];

 if(['armor','helmet','backpack'].includes(item.category)){
  const base=String(item.baseId??item.id);
  const match=base.match(/-(\d+)(?:-|$)/);
  const raw=Number(
   item.equipmentLevel ??
   match?.[1] ??
   (item.tier===7?6:item.tier) ??
   1
  );
  const level=Math.min(6,Math.max(1,raw||1));

  return item.quality==='gold'
   ?`${level}등급 · 골드`
   :`${level}등급`;
 }

 return item.quality==='gold'
  ?item.category==='weapon'
   ?'정밀 · 골드'
   :'골드'
  :item.quality
   ?QUALITY_LABELS[item.quality]
   :`${item.tier}등급`;
}

